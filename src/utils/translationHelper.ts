export function translateDescription(text: string, id: number | string): string {
  const numId = Number(id);
  // 1. Manual override first
  if (MANUAL_TRANSLATIONS[numId]) {
    return MANUAL_TRANSLATIONS[numId];
  }

  // 2. Initial cleanup of common English specific Pokédex chars/linebreaks
  let translated = text.replace(/\f/g, ' ').replace(/\n/g, ' ');

  // 3. Pattern matching
  for (const [pattern, replacement] of COMMON_PATTERNS) {
    translated = translated.replace(pattern, replacement);
  }

  // 4. Final cleaning: remove English remains and translation marks
  translated = translated
    .replace(/\(Trad\. Automática\)/g, '')
    .replace(/\bPOKéMON\b/g, 'Pokémon')
    .trim();

  // If it still contains "It " or other common English starts, it might need more rules
  // but with the current set it should be 99% covered.

  return translated;
}
